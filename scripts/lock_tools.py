"""Resolve exact dev tooling and hash all non-yanked PyPI release artifacts."""

import argparse
import json
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path
from typing import TypedDict, cast

DIRECT = [
    "pytest==9.0.2",
    "ruff==0.14.3",
    "mypy==1.18.2",
    "build==1.3.0",
    "setuptools==80.9.0",
    "wheel==0.45.1",
    "exchange-calendars==4.11.2",
    "pyarrow==21.0.0",
    "numpy==2.3.4",
    "pandas==2.3.3",
    "tzdata==2025.2",
    "pyspark==4.3.0",
]
ROOT = Path(__file__).resolve().parents[1]


class Metadata(TypedDict):
    name: str
    version: str


class Install(TypedDict):
    metadata: Metadata


class Report(TypedDict):
    install: list[Install]


class Artifact(TypedDict):
    yanked: bool
    digests: dict[str, str]


class Release(TypedDict):
    urls: list[Artifact]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upgrade", action="store_true", help="Resolve fresh transitive versions")
    args = parser.parse_args()
    lock = ROOT / "requirements-dev.lock"
    with tempfile.TemporaryDirectory() as temporary:
        report_path = Path(temporary) / "report.json"
        command = [
            sys.executable,
            "-m",
            "pip",
            "install",
            "--dry-run",
            "--ignore-installed",
            "--disable-pip-version-check",
            "--report",
            str(report_path),
        ]
        if lock.exists() and not args.upgrade:
            # A constraints file retains versions without activating hash mode.
            constraints = Path(temporary) / "constraints.txt"
            constraints.write_text(
                "\n".join(
                    line.split(" ")[0]
                    for line in lock.read_text().splitlines()
                    if line and not line.startswith(("#", " "))
                ),
                encoding="utf-8",
            )
            command.extend(["--constraint", str(constraints)])
        subprocess.run([*command, *DIRECT], check=True)
        report = cast(Report, json.loads(report_path.read_text(encoding="utf-8")))
    # colorama is conditional on Windows in pytest/build; include it explicitly so
    # a Linux-generated lock is installable on Windows too.
    packages = {item["metadata"]["name"]: item["metadata"]["version"] for item in report["install"]}
    packages.setdefault("colorama", "0.4.6")
    lines = [
        "# CPython 3.11, Windows/Linux development and build tooling.",
        "# Generated by scripts/lock_tools.py; all non-yanked release hashes from PyPI.",
        "# Includes optional ingestion and Spark Batch dependencies. Review changes and",
        "# rerun platform checks.",
    ]
    for name, version in sorted(packages.items(), key=lambda pair: pair[0].lower()):
        with urllib.request.urlopen(
            f"https://pypi.org/pypi/{name}/{version}/json", timeout=30
        ) as response:
            release = cast(Release, json.load(response))
        hashes = sorted(
            {
                artifact["digests"]["sha256"]
                for artifact in release["urls"]
                if not artifact["yanked"]
            }
        )
        if not hashes:
            raise RuntimeError(f"No usable release artifacts: {name}")
        lines.append(f"{name}=={version} \\")
        for index, digest in enumerate(hashes):
            continuation = " \\" if index < len(hashes) - 1 else ""
            lines.append(f"    --hash=sha256:{digest}{continuation}")
    # Replace only after all metadata has been obtained successfully.
    staged = lock.with_suffix(".lock.tmp")
    staged.write_text("\n".join(lines) + "\n", encoding="utf-8")
    staged.replace(lock)


if __name__ == "__main__":
    main()
